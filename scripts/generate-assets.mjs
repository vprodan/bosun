// Build-time only. Runtime assets are literals, independent of checkout paths and HOME.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
function read(file) {
  const stat = fs.lstatSync(file);
  if (!stat.isFile() || stat.isSymbolicLink() || stat.size > 131072)
    throw new Error("Invalid build asset");
  return fs.readFileSync(file, "utf8");
}
function collect(root, assets, directory, depth = 0) {
  if (depth > 16 || Object.keys(assets).length > 256)
    throw new Error("Build assets exceed bounds");
  const stat = fs.lstatSync(directory);
  if (!stat.isDirectory() || stat.isSymbolicLink())
    throw new Error("Invalid build asset directory");
  for (const entry of fs
    .readdirSync(directory, { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) collect(root, assets, file, depth + 1);
    else if (entry.isFile() && entry.name.endsWith(".md"))
      assets[path.relative(root, file).split(path.sep).join("/")] = read(file);
    else throw new Error("Unexpected build asset");
  }
}
export function renderAssets(root) {
  const assets = {};
  collect(root, assets, path.join(root, "roles"));
  collect(root, assets, path.join(root, "skills"));
  assets["policy.md"] = read(path.join(root, "policy.md"));
  const version = JSON.parse(read(path.join(root, "package.json"))).version;
  if (
    typeof version !== "string" ||
    !/^\d+\.\d+\.\d+(?:[-+][a-zA-Z0-9.-]+)?$/.test(version)
  )
    throw new Error("Invalid package version");
  if (
    Object.keys(assets).length > 256 ||
    Object.values(assets).reduce(
      (size, text) => size + Buffer.byteLength(text),
      0,
    ) >
      8 * 1024 * 1024
  )
    throw new Error("Build assets exceed bounds");
  const content = `// Generated by sh scripts/bun-check.sh assets; edit roles/, skills/, policy.md or package.json.\nexport const BUILD_VERSION = ${JSON.stringify(version)};\nexport const TEXT_ASSETS: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(assets, null, 2)});\n`;
  return { version, assets, content };
}
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  const root = path.resolve(import.meta.dirname, "..");
  const { version, assets, content } = renderAssets(root);
  fs.writeFileSync(
    path.join(root, "src", "platform", "generated-assets.ts"),
    content,
  );
  console.log(
    `Embedded ${Object.keys(assets).length} text assets for bosun ${version}.`,
  );
}
